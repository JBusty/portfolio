// Regenerates lib/imageMeta.ts — intrinsic dimensions for everything in public/images.
// next/image needs real width/height to reserve layout space and preserve aspect ratio.
// Run with: node scripts/gen-image-meta.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, posix } from 'node:path';

const ROOT = 'public/images';

function pngSize(buf) {
  // IHDR width/height live at byte offsets 16 and 20.
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
}

function jpgSize(buf) {
  let i = 2;
  while (i < buf.length) {
    if (buf[i] !== 0xff) { i += 1; continue; }
    const marker = buf[i + 1];
    // SOF0/1/2/3 carry the frame dimensions.
    if (marker >= 0xc0 && marker <= 0xc3) {
      return { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
    }
    i += 2 + buf.readUInt16BE(i + 2);
  }
  return null;
}

function svgSize(text) {
  const viewBox = text.match(/viewBox="\s*[\d.-]+[\s,]+[\d.-]+[\s,]+([\d.]+)[\s,]+([\d.]+)/);
  if (viewBox) return { w: Math.round(+viewBox[1]), h: Math.round(+viewBox[2]) };
  const w = text.match(/\bwidth="([\d.]+)/);
  const h = text.match(/\bheight="([\d.]+)/);
  return w && h ? { w: Math.round(+w[1]), h: Math.round(+h[1]) } : null;
}

function sizeOf(file) {
  if (file.endsWith('.png')) return pngSize(readFileSync(file));
  if (file.endsWith('.jpg') || file.endsWith('.jpeg')) return jpgSize(readFileSync(file));
  if (file.endsWith('.svg')) return svgSize(readFileSync(file, 'utf8'));
  return null;
}

const entries = [];
function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) { walk(full); continue; }
    const size = sizeOf(full);
    if (!size) continue;
    const url = '/' + posix.join(...full.split(/[\\/]/).slice(1));
    entries.push([url, size]);
  }
}
walk(ROOT);

const body = entries.map(([url, s]) => `  '${url}': { w: ${s.w}, h: ${s.h} },`).join('\n');

writeFileSync(
  'lib/imageMeta.ts',
  `// GENERATED by scripts/gen-image-meta.mjs — do not edit by hand.
// Re-run after adding or replacing anything in public/images.

export interface ImageMeta {
  w: number;
  h: number;
}

export const IMAGE_META: Record<string, ImageMeta> = {
${body}
};

/** Intrinsic dimensions for a public/images path. Falls back to 16:9 for unknown files. */
export function imageMeta(src: string): ImageMeta {
  return IMAGE_META[src] ?? { w: 1600, h: 900 };
}
`,
  'utf8',
);

console.log(`wrote lib/imageMeta.ts with ${entries.length} entries`);
